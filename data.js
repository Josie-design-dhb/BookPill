/* ========== 纸上良方 · 本地数据层 v2.1 ========== */
var BookPillData = (function(){
  var KEY = 'bookpill_submissions';
  var CONTRIBUTOR_PROFILE_KEY = 'bookpill_contributor_profile_v2';

  function _read(){
    try{
      var raw = localStorage.getItem(KEY);
      if(!raw) return [];
      var data = JSON.parse(raw);
      return Array.isArray(data) ? data : [];
    }catch(e){ return []; }
  }

  function _write(arr){
    try{
      localStorage.setItem(KEY, JSON.stringify(arr));
      return true;
    }catch(e){ return false; }
  }

  function _id(){
    return 'sub_' + Date.now().toString(36) + Math.random().toString(36).slice(2,6);
  }

  /* ========== CRUD ========== */

  function getAll(){
    return _read().sort(function(a,b){
      return new Date(b.createdAt) - new Date(a.createdAt);
    });
  }

  function getById(id){
    return _read().find(function(s){ return s.id === id; });
  }

  function add(submission){
    var arr = _read();
    var now = new Date().toISOString();
    var item = {
      id: submission.id || _id(),
      title: submission.title || '',
      author: submission.author || '',
      domain: submission.domain || '',
      scene: submission.scene || '',
      insight: submission.insight || '',
      bookDesc: submission.bookDesc || '',
      prescription: submission.prescription || '',
      quote: submission.quote || '',
      audience: submission.audience || '',
      contributor: submission.contributor || '',
      note: submission.note || '',
      tags: submission.tags || [],
      publisher: submission.publisher || '',
      pageCount: submission.pageCount || 0,
      publishedDate: submission.publishedDate || '',
      language: submission.language || '',
      isbn: submission.isbn || '',
      steps: submission.steps || [],
      keywordsMatched: submission.keywordsMatched || [],
      autoGenerated: submission.autoGenerated || {},
      status: submission.status || 'pending',
      createdAt: submission.createdAt || now,
      updatedAt: submission.updatedAt || now
    };
    arr.push(item);
    _write(arr);
    return item;
  }

  function update(id, fields){
    var arr = _read();
    var idx = arr.findIndex(function(s){ return s.id === id; });
    if(idx < 0) return null;
    for(var k in fields){
      if(fields.hasOwnProperty(k)) arr[idx][k] = fields[k];
    }
    arr[idx].updatedAt = new Date().toISOString();
    _write(arr);
    return arr[idx];
  }

  function setStatus(id, status){
    return update(id, { status: status });
  }

  function remove(id){
    var arr = _read();
    var filtered = arr.filter(function(s){ return s.id !== id; });
    _write(filtered);
    return arr.length !== filtered.length;
  }

  function clear(){
    return _write([]);
  }

  /* ========== Counts & Stats ========== */

  function count(){
    return _read().length;
  }

  function countByStatus(status){
    return _read().filter(function(s){ return s.status === status; }).length;
  }

  function countByDomain(domain){
    return _read().filter(function(s){ return s.domain === domain; }).length;
  }

  function getDomainBreakdown(){
    var arr = _read();
    var map = {};
    arr.forEach(function(s){
      var d = s.domain || '未分';
      if(!map[d]) map[d] = { domain: d, count: 0, pending: 0, accepted: 0, rejected: 0 };
      map[d].count++;
      var st = s.status || 'pending';
      map[d][st] = (map[d][st] || 0) + 1;
    });
    return Object.values(map).sort(function(a,b){ return b.count - a.count; });
  }

  function getMonthlyTrend(months){
    months = months || 6;
    var arr = _read();
    var buckets = [];
    var now = new Date();
    for(var i = months - 1; i >= 0; i--){
      var d = new Date(now.getFullYear(), now.getMonth() - i, 1);
      buckets.push({
        label: (d.getMonth() + 1) + '月',
        year: d.getFullYear(),
        m: d.getMonth(),
        count: 0
      });
    }
    arr.forEach(function(s){
      var d = new Date(s.createdAt);
      for(var i = 0; i < buckets.length; i++){
        if(d.getFullYear() === buckets[i].year && d.getMonth() === buckets[i].m){
          buckets[i].count++;
          break;
        }
      }
    });
    return buckets;
  }

  function getContributorRanking(limit){
    limit = limit || 10;
    var arr = _read();
    var map = {};
    arr.forEach(function(s){
      var name = s.contributor || '匿名';
      if(!map[name]){
        map[name] = {
          name: name,
          count: 0,
          accepted: 0,
          pending: 0,
          rejected: 0,
          domains: {},
          latest: s.createdAt,
          first: s.createdAt
        };
      }
      map[name].count++;
      var st = s.status || 'pending';
      map[name][st] = (map[name][st] || 0) + 1;
      if(s.domain){
        map[name].domains[s.domain] = (map[name].domains[s.domain] || 0) + 1;
      }
      if(new Date(s.createdAt) > new Date(map[name].latest)) map[name].latest = s.createdAt;
      if(new Date(s.createdAt) < new Date(map[name].first)) map[name].first = s.createdAt;
    });
    return Object.values(map).sort(function(a,b){
      if(b.accepted !== a.accepted) return b.accepted - a.accepted;
      return b.count - a.count;
    }).slice(0, limit);
  }

  function getContributors(){
    var arr = _read();
    var map = {};
    arr.forEach(function(s){
      var name = s.contributor || '匿名';
      if(!map[name]) map[name] = { name: name, count: 0, latest: s.createdAt };
      map[name].count++;
      if(new Date(s.createdAt) > new Date(map[name].latest)) map[name].latest = s.createdAt;
    });
    return Object.values(map).sort(function(a,b){ return b.count - a.count; });
  }

  function getTagCloud(){
    var arr = _read();
    var map = {};
    arr.forEach(function(s){
      var tags = s.tags || [];
      tags.forEach(function(t){
        if(!t) return;
        map[t] = (map[t] || 0) + 1;
      });
      if(s.domain) map['域·' + s.domain] = (map['域·' + s.domain] || 0) + 1;
    });
    return Object.entries(map)
      .map(function(e){ return { tag: e[0], count: e[1] }; })
      .sort(function(a,b){ return b.count - a.count; })
      .slice(0, 40);
  }

  function getSummaryStats(){
    var arr = _read();
    var total = arr.length;
    var pending = arr.filter(function(s){ return s.status === 'pending'; }).length;
    var accepted = arr.filter(function(s){ return s.status === 'accepted'; }).length;
    var rejected = arr.filter(function(s){ return s.status === 'rejected'; }).length;
    var uniqueContributors = {};
    arr.forEach(function(s){ uniqueContributors[s.contributor || '匿名'] = true; });
    var contribCount = Object.keys(uniqueContributors).length;
    var domains = getDomainBreakdown();
    var last7 = 0;
    var cutoff = Date.now() - 7 * 86400 * 1000;
    arr.forEach(function(s){ if(new Date(s.createdAt).getTime() >= cutoff) last7++; });
    var acceptRate = total > 0 ? Math.round((accepted / total) * 100) : 0;
    return {
      total: total,
      pending: pending,
      accepted: accepted,
      rejected: rejected,
      uniqueContributors: contribCount,
      domainCount: domains.length,
      last7: last7,
      acceptRate: acceptRate,
      byDomain: domains,
      monthly: getMonthlyTrend(6)
    };
  }

  /* ========== Contributor Profile (local memory) ========== */

  function getContributorProfile(){
    try{
      var raw = localStorage.getItem(CONTRIBUTOR_PROFILE_KEY);
      if(!raw) return null;
      return JSON.parse(raw);
    }catch(e){ return null; }
  }

  function setContributorProfile(profile){
    try{
      localStorage.setItem(CONTRIBUTOR_PROFILE_KEY, JSON.stringify(profile));
      return true;
    }catch(e){ return false; }
  }

  function clearContributorProfile(){
    try{
      localStorage.removeItem(CONTRIBUTOR_PROFILE_KEY);
      return true;
    }catch(e){ return false; }
  }

  /* ========== Export ========== */

  function exportJSON(){
    return JSON.stringify(_read(), null, 2);
  }

  function exportCSV(){
    var arr = _read();
    var headers = ['id','title','author','domain','scene','insight','bookDesc','prescription','quote','audience','contributor','note','tags','publisher','pageCount','publishedDate','language','isbn','status','createdAt','updatedAt'];
    var lines = [headers.join(',')];
    arr.forEach(function(s){
      var row = headers.map(function(h){
        var val;
        if(h === 'tags'){
          val = (s.tags || []).join('|');
        }else{
          val = (s[h] || '').toString();
        }
        if(val.indexOf(',') >= 0 || val.indexOf('"') >= 0 || val.indexOf('\n') >= 0){
          val = '"' + val.replace(/"/g, '""') + '"';
        }
        return val;
      });
      lines.push(row.join(','));
    });
    return lines.join('\n');
  }

  function exportMarkdownSummary(){
    var stats = getSummaryStats();
    var contr = getContributorRanking(5);
    var lines = [];
    lines.push('# 纸上良方 · 社区共建统计报告');
    lines.push('');
    lines.push('生成时间：' + new Date().toLocaleString('zh-CN'));
    lines.push('');
    lines.push('## 概览');
    lines.push('');
    lines.push('- **总投稿数**：' + stats.total);
    lines.push('- **已收录**：' + stats.accepted + '（收录率 ' + stats.acceptRate + '%）');
    lines.push('- **待审核**：' + stats.pending);
    lines.push('- **未通过**：' + stats.rejected);
    lines.push('- **投稿人数**：' + stats.uniqueContributors);
    lines.push('- **覆盖问题域**：' + stats.domainCount + ' 个');
    lines.push('- **近 7 天新增**：' + stats.last7);
    lines.push('');
    lines.push('## 各脉投稿分布');
    lines.push('');
    stats.byDomain.forEach(function(d){
      lines.push('- **' + d.domain + '**：' + d.count + '（收录 ' + d.accepted + ' / 待审 ' + d.pending + '）');
    });
    lines.push('');
    lines.push('## 贡献榜 Top 5');
    lines.push('');
    contr.forEach(function(c, i){
      lines.push((i+1) + '. **' + c.name + '**：累计投稿 ' + c.count + ' 本，收录 ' + c.accepted + ' 本');
    });
    return lines.join('\n');
  }

  return {
    getAll: getAll,
    getById: getById,
    add: add,
    update: update,
    setStatus: setStatus,
    remove: remove,
    clear: clear,
    count: count,
    countByStatus: countByStatus,
    countByDomain: countByDomain,
    getDomainBreakdown: getDomainBreakdown,
    getMonthlyTrend: getMonthlyTrend,
    getContributors: getContributors,
    getContributorRanking: getContributorRanking,
    getTagCloud: getTagCloud,
    getSummaryStats: getSummaryStats,
    getContributorProfile: getContributorProfile,
    setContributorProfile: setContributorProfile,
    clearContributorProfile: clearContributorProfile,
    exportJSON: exportJSON,
    exportCSV: exportCSV,
    exportMarkdownSummary: exportMarkdownSummary,
    KEY: KEY,
    CONTRIBUTOR_PROFILE_KEY: CONTRIBUTOR_PROFILE_KEY
  };


})();
