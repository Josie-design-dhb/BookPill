function searchLocalCatalog(query){
  if(!query || !query.trim()) return [];
  var q = query.trim().toLowerCase();
  var tokens = q.split(/\s+/);
  var results = [];
  for(var i = 0; i < LOCAL_BOOK_CATALOG.length; i++){
    var b = LOCAL_BOOK_CATALOG[i];
    var haystack = (b.title + ' ' + (b.author || '') + ' ' + (b.publisher || '')).toLowerCase();
    var score = 0;
    var matched = false;
    if(haystack.indexOf(q) >= 0){
      score += 100; matched = true;
    }
    for(var t = 0; t < tokens.length; t++){
      if(tokens[t] && haystack.indexOf(tokens[t]) >= 0){
        score += 20;
      }
    }
    if(b.domain){
      for(var d = 0; d < b.domain.length; d++){
        if(q.indexOf(b.domain[d]) >= 0 || b.domain[d].indexOf(q) >= 0){
          score += 5; matched = true;
        }
      }
    }
    if(matched || score > 0){
      b._score = score;
      results.push(b);
    }
  }
  results.sort(function(a,b){ return (b._score || 0) - (a._score || 0); });
  return results.slice(0, 5);
}

function lookupLocalCatalog(title, author){
  var results = searchLocalCatalog((title || '') + ' ' + (author || ''));
  if(results.length === 0 && title){
    results = searchLocalCatalog(title);
  }
  if(results.length === 0) return null;
  var best = results[0];
  return {
    title: best.title,
    authors: best.author || '',
    desc: (best.desc || '').substring(0, 500),
    categories: best.categories || [],
    pageCount: best.pageCount || 0,
    publishedDate: best.publishedDate || '',
    publisher: best.publisher || '',
    language: best.language || '',
    isbn: best.isbn || '',
    cover: '',
    _local: true,
    _preDomains: best.domain || []
  };
}


