// 繁简转换函数（按字符串长度降序排列，优先匹配多字词）
function toSimplified(text) {
  if (!text) return text;
  // 按 key 长度降序，避免 "那麼" 被 "麼" 先替换成 "那幺"
  const keys = Object.keys(TRAD_TO_SIMP).sort((a, b) => b.length - a.length);
  let result = text;
  for (const trad of keys) {
    const simp = TRAD_TO_SIMP[trad];
    if (trad !== simp) {
      result = result.split(trad).join(simp);
    }
  }
  return result;
}

// 后处理：清理末尾多余问号（Step2/3 禁止追问）
function cleanTrailingQuestion(text) {
  if (!text) return text;
  // 去掉最后一个段落末尾的问号，改成句号
  return text.replace(/([？?])\s*$/g, '。');
}

// 后处理：清理模型可能原样输出的结构标记（Step2/3/4 都清理）
function cleanStructuralMarkers(text) {
  if (!text) return text;
  return text
    // 第X段 · xxx / 第X步 · xxx / 第一段 · 问题拆解 等
    .replace(/^\s*第?[一二三四五六七八九十\d]+[段步部分]\s*[·.．:：]\s*[^\n]*$/gm, '')
    // 纯标题词单独一行
    .replace(/^\s*(问题拆解|处方笺格式|收尾要点|第一段|第二段|第三段|第四段|分析|诊断|拆解|原因分析|建议|方案|行动鼓励|下一步)\s*[·.．:：]?\s*$/gm, '')
    // 【xxx】单独一行
    .replace(/^\s*[【\[]+[^】\]]+[】\]]+\s*$/gm, '')
    // 多余空行
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

